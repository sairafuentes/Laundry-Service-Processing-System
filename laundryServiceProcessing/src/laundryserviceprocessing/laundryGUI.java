    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        

    if (queue.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "No pending laundry orders!");
        return;
    }

    laundryOrder processedOrder = queue.dequeue();

    if (processedOrder != null) {

        processedOrder.setStatus("Completed");

        refreshTable();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "ORDER PROCESSED SUCCESSFULLY!\n\n"
                + "Transaction ID: "
                + processedOrder.getTransactionID()
                + "\nCustomer Name: "
                + processedOrder.getCustomerName()
                + "\nWeight: "
                + processedOrder.getWeight() + " kg"
                + "\nService: "
                + processedOrder.getServiceType()
                + "\nStatus: "
                + processedOrder.getStatus()
        );
    }
// TODO add your handling code here:
    }//GEN-LAST:event_btnProcessActionPerformed

