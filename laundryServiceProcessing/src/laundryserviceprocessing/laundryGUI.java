    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
       

    String id = txtID.getText().trim();
    String name = txtName.getText().trim();
    String weightText = txtWeight.getText().trim();

    if (id.isEmpty() || name.isEmpty() || weightText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Please fill in all fields!");
        return;
    }

    try {
        double weight = Double.parseDouble(weightText);

        String service = cmbServiceType.getSelectedItem().toString();

        laundryOrder order;

        if (service.equals("Wash and Dry")) {
            order = new washAndDry(id, name, weight);
        } else {
            order = new washAndFold(id, name,weight);
        }

        if (queue.enqueue(order)) {

            refreshTable();

            javax.swing.JOptionPane.showMessageDialog(
                    this, "Order successfully registered!");

            clearFields();

        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Duplicate Transaction ID or Queue is Full!");
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Please enter a valid weight!");

    } catch (IllegalArgumentException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, e.getMessage());
    }
// TODO add your handling code here:
    }//GEN-LAST:event_btnRegisterActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
       

    String searchID = txtSearch.getText().trim();

    if (searchID.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Please enter a Transaction ID!");
        return;
    }

    laundrySearch search = new laundrySearch();

    laundryOrder result =
            search.searchByTransactionID(queue, searchID);

    if (result != null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "LAUNDRY ORDER FOUND!\n\n"
                + "Transaction ID: "
                + result.getTransactionID()
                + "\nCustomer Name: "
                + result.getCustomerName()
                + "\nWeight: " + result.getWeight() + " kg"
                + "\nService: " + result.getServiceType()
                + "\nStatus: " + result.getStatus()
        );

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Transaction ID not found!");
    }// TODO add your handling code here:
    }//GEN-LAST:event_btnSearchActionPerformed


// ADD REFRESH TABLE HERE
private void refreshTable() {

    tableModel.setRowCount(0);

    for (int i = 0; i < queue.getCount(); i++) {

        laundryOrder order = queue.getOrderAt(i);

        tableModel.addRow(new Object[]{
            order.getTransactionID(),
            order.getCustomerName(),
            order.getWeight(),
            order.getServiceType(),
            order.getStatus()
        });
    }
}

